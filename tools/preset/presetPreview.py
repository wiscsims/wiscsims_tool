from this import d
from PyQt5.QtCore import QVariant
from PyQt5.QtGui import QColor
from qgis.core import (
    QgsDataProvider,
    QgsDrawSourceEffect,
    QgsDropShadowEffect,
    QgsEffectStack,
    QgsFeature,
    QgsField,
    QgsGeometry,
    QgsMapLayer,
    QgsMarkerSymbol,
    QgsPalLayerSettings,
    QgsProject,
    QgsPropertyCollection,
    QgsVectorLayer,
    QgsVectorLayerSimpleLabeling,
    Qgis,
)


class PresetPreview:
    """Docstring for PreviewLayer."""

    def __init__(self, preset_layer):
        self.preview_layer: QgsVectorLayer = None
        self.sc_dp: QgsDataProvider = None
        self.preset_layer: QgsVectorLayer = preset_layer
        self.cleanup_old_layers()

        self.scale = 1
        self.spot_size = 10

        # if self.preset_layer:
        self.create()

        self.colors = {
            "spot_fill_normal": QColor(64, 143, 176, 102),  # light blue
            "spot_stroke": QColor(255, 255, 255),  # white
            "spot_fill_move": QColor(96, 180, 84, 102),  # vegas gold
            "comment_stroke": QColor(255, 255, 255),  # white
            "comment_fill": QColor(255, 0, 0),  # white
        }

    def __del__(self):
        self.cleanup_old_layers()

    def create(self):
        self.cleanup_old_layers()
        self.preview_layer = QgsVectorLayer("Point", "tmp", "memory")

        self.preview_layer.startEditing()
        self.preview_layer.setFlags(QgsMapLayer.Private)
        self.preview_layer.setCustomProperty("skipMemoryLayersCheck", 1)

        renderer = self.preview_layer.renderer()

        if self.preset_layer:
            # Copy and paste symbol sytle from preset layer
            symbol = self.preset_layer.renderer().symbol()
            props = symbol.symbolLayer(0).properties()
        else:
            # spotSize = 1.0 * self.dock.Spn_Spot_Size.value()
            # if self.model.isAvailable():
            #     scale = self.get_average(self.model.getScales())
            # else:
            #     scale = 1.0
            # scale = self.ct[self.getNavAlign()].scale / 1.0
            # props["size"] = str(spotSize / scale)
            props = renderer.symbol().symbolLayer(0).properties()

        props["size"] = f"{1.0 * self.scale * self.spot_size}"
        props["name"] = "circle"
        props["size_unit"] = "MapUnit"
        props["offset_unit"] = "MapUnit"
        props["outline_width_unit"] = "MapUnit"
        mySimpleSymbol = QgsMarkerSymbol.createSimple(props)
        renderer.setSymbol(mySimpleSymbol)

        # black
        renderer.symbol().symbolLayer(0).setStrokeColor(QColor(255, 255, 255))
        # light blue
        renderer.symbol().setColor(QColor(64, 143, 176, 102))

        self.sc_dp = self.preview_layer.dataProvider()

        # add "Comment" field to the attribute table
        self.sc_dp.addAttributes([QgsField("Comment", QVariant.String)])

        # Label formatting:
        #   "Comment" field,
        #   diplay all comments,
        #   drop shodow,
        #   buffer (white)
        #
        settings = QgsPalLayerSettings()
        # print(dir(settings))
        settings.enabled = True
        settings.fieldName = "Comment"
        settings.displayAll = True
        coll = QgsPropertyCollection("preview")
        coll.setProperty(settings.Size, 20)
        # coll.setProperty(settings.ShadowDraw, True)
        # coll.setProperty(settings.Color, QColor(255, 255, 255)) # <- whilte
        coll.setProperty(settings.Color, QColor(255, 0, 0))

        coll.setProperty(settings.BufferDraw, True)
        # coll.setProperty(settings.BufferColor, QColor(0, 0, 0))
        coll.setProperty(settings.BufferColor, QColor(255, 255, 255))

        # rendering: overlap
        plmt = settings.placementSettings()
        plmt.setOverlapHandling(Qgis.LabelOverlapHandling.AllowOverlapAtNoCost)
        settings.setPlacementSettings(plmt)

        # placement: obstacle
        obs = settings.obstacleSettings()
        obs.setIsObstacle(False)
        settings.setObstacleSettings(obs)

        settings.setDataDefinedProperties(coll)
        self.preview_layer.setLabelsEnabled(False)  # TODO
        self.preview_layer.setLabeling(QgsVectorLayerSimpleLabeling(settings))
        self.preview_layer.updateExtents()
        self.preview_layer.commitChanges()

        # add drop shadow and color to the spot preview
        pe_stack = QgsEffectStack()
        pe_stack.appendEffect(QgsDropShadowEffect())
        pe_stack.appendEffect(QgsDrawSourceEffect())

        renderer.setPaintEffect(pe_stack)

        self.fields = self.preview_layer.fields()

        self.feature_id = None

        self.preview_layer.triggerRepaint()
        QgsProject.instance().addMapLayer(self.preview_layer)

    def reset(self, moving=False):
        self.remove_objects()
        if self.preview_layer is None:
            self.create()
            return

        symbol = self.preview_layer.renderer().symbol()
        symbol.symbolLayer(0).setStrokeColor(QColor(255, 255, 255))  # stroke: while
        if moving:
            symbol.setColor(QColor(96, 180, 84, 102))  # fill: vegas yellow?
        else:
            symbol.setColor(QColor(64, 143, 176, 102))  # fill: light blue

    def update_layer(self, new_layer):
        self.preset_layer = new_layer

    def cleanup_old_layers(self):
        instance = QgsProject.instance()
        vals = instance.mapLayers().values()
        [
            instance.removeMapLayer(layer)
            for layer in vals
            if layer.name() == "tmp" and layer.storageType() == "Memory storage"
        ]

    def create_feature(self, pt, comment):
        geom = QgsGeometry.fromPointXY(pt)
        feature = QgsFeature()
        feature.setFields(self.fields)
        feature.setGeometry(geom)
        feature["Comment"] = comment
        return feature

    def add_points(self, points):
        features = []
        for pt, comment in points:
            feature = self.create_feature(pt, comment)
            features.append(feature)

        self.sc_dp.addFeatures(features)
        self.preview_layer.commitChanges()
        self.preview_layer.triggerRepaint()

    def remove_objects(self):
        if self.preset_layer is None:
            return

        self.preset_layer.removeSelection()
        if self.sc_dp is None:
            return

        feature_ids = [f.id() for f in self.sc_dp.getFeatures()]
        if len(feature_ids) == 0:
            return
        self.preview_layer.startEditing()
        self.sc_dp.deleteFeatures(feature_ids)
        self.preview_layer.commitChanges()
        self.preview_layer.triggerRepaint()

    def update_comment(self, comment):
        field_index = self.preview_layer.fields().indexOf("Comment")
        features = self.preview_layer.getFeatures()
        feature_list = [f for f in features]
        if len(feature_list) == 0:
            return
        feature_id = feature_list[0].id()
        self.preview_layer.startEditing()
        self.preview_layer.changeAttributeValue(feature_id, field_index, comment)
        self.preview_layer.commitChanges()
        self.preview_layer.triggerRepaint()

    def update_symbol_size(self, scale, spot_size):
        # get symbol information from preset layer
        if self.preview_layer is None:
            return

        # size = 10
        #
        # if self.preset_layer:
        #     symbol = self.preset_layer.renderer().symbol()
        #     props = symbol.symbolLayer(0).properties()
        #     size = props["size"]

        self.scale = scale
        self.spot_size = spot_size
        size = 1.0 * self.scale * self.spot_size

        sc_props = self.preview_layer.renderer().symbol().symbolLayer(0).properties()
        sc_props["size"] = size
        self.preview_layer.renderer().setSymbol(QgsMarkerSymbol.createSimple(sc_props))
        self.preview_layer.triggerRepaint()

    def update_position(self, pt):
        geom = QgsGeometry.fromPointXY(pt)
        feature_id = [f.id() for f in self.sc_dp.getFeatures()]

        if len(feature_id) == 0:
            return

        self.sc_dp.changeGeometryValues({feature_id[0]: geom})
        self.preview_layer.triggerRepaint()

    def disable_comment_preview(self):
        self.preview_layer.setLabelsEnabled(False)
        self.preview_layer.updateExtents()
        self.preview_layer.commitChanges()

    def toggle_comment_preview(self):
        current_status = self.preview_layer.labelsEnabled()
        print("xxxxxxxxxxxxxx", current_status)
        self.preview_layer.setLabelsEnabled(not current_status)  # TODO
        self.preview_layer.updateExtents()
        self.preview_layer.commitChanges()
