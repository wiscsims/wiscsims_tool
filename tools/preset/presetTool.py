class PresetTool(QObject):
    """Coordinate Preset controls, placement previews and spot editing."""

    setActiveLayer = pyqtSignal(QgsVectorLayer)
    undo_max: int = 100
    max_preset_points: int = 5000
    line_preview_interval: float = 0.05

    def __init__(self, dock, canvas):
        super().__init__(dock)

        self.reorder_preview = False

        self.canvas = canvas
        self.dock = dock
        self._canvas_connections = SignalConnections()

        self.lt = LayerTool()
        self.preset_layer = self.get_preset_layer()

        self.preview = PresetPreview(self.preset_layer, self.canvas)

        self.rb_line = QgsRubberBand(self.canvas, QgsWkbTypes.LineGeometry)
        self.start_point = []
        self.end_point = []
        self.line_in_progress = False
        self.last_line_preview_at = 0.0

        self.preset_points = []
        self.undo_preset = []

        self.scale = 1

        self.feature_id = None
        self.movement_offset = [0, 0]
        self.shift_key = False
        self.alt_key = False

        self.mouse_left = False

        self.relocating_spot = False
        self.cursor_pos = QgsPointXY(0, 0)

        self.active = False

        self.preset_modes = ["point", "line", "grid"]
        self.current_preset_mode = "point"

        self.init_preset_layer_combobox()
        self.initialize_ui()

        self.dock.Tab_Preset_Mode.setCurrentIndex(self.preset_modes.index(self.current_preset_mode))
        self.handle_preset_mode_changed(self.preset_modes.index(self.current_preset_mode))

    def initialize_ui(self):
        # Preset
        ## Comment
        self.dock.Tbx_Comment.textChanged.connect(self.reset_current_number)
        self.dock.Tbx_Comment.textChanged.connect(self.handle_comment_change_preview)
        self.dock.Spn_Current_Number.valueChanged.connect(self.handle_comment_change_preview)
        self.dock.Cbx_Number_Increment.toggled.connect(self.handle_comment_change_preview)
        self.dock.Btn_Reset_Current_Number.clicked.connect(self.reset_current_number)

        ## Layer
        self.dock.Btn_Create_Preset_Layer.clicked.connect(self.create_preset_layer)
        self.dock.Cmb_Preset_Layer.currentIndexChanged.connect(self.handle_change_preset_layer)

        ## Scale
        self.dock.Spn_Preset_Pixel_Size.valueChanged.connect(self.handle_change_pixel_size)
        self.dock.Spn_Preset_Spot_Size.valueChanged.connect(self.handle_change_spot_size)

        ## Mode
        self.dock.Tab_Preset_Mode.currentChanged.connect(self.handle_preset_mode_changed)

        ### Point
        self.dock.Opt_Point_Preview.stateChanged.connect(self.handle_change_PointPreview)
        self.dock.Opt_Comment_Preview.stateChanged.connect(self.handle_change_CommentPreview)
        self.preview.set_text_preview(self.dock.Opt_Comment_Preview.isChecked())

        ### Line
        self.dock.Opt_Line_Step_Size.toggled.connect(self.handle_line_spacing_mode_changed)
        self.dock.Spn_Line_Step_Size.valueChanged.connect(self.update_line)
        self.dock.Spn_Line_N_Spot.valueChanged.connect(self.update_line)
        self.dock.Btn_Line_Add_Points.clicked.connect(self.add_preset_points)

        ### Grid
        self.dock.Spn_Grid_Step_Size_X.valueChanged.connect(self.update_grid)
        self.dock.Spn_Grid_Step_Size_Y.valueChanged.connect(self.update_grid)
        self.dock.Spn_Grid_N_Point_X.valueChanged.connect(self.update_grid)
        self.dock.Spn_Grid_N_Point_Y.valueChanged.connect(self.update_grid)
        self.dock.Cmb_Grid_Move_Order.currentIndexChanged.connect(self.update_grid)
        self.dock.Btn_Grid_Add_Points.clicked.connect(self.add_preset_points)
        self._canvas_connections.connect(self.canvas.rotationChanged, self.update_grid)

        ## Undo
        self.dock.Btn_Undo_Add_Preset_Point.clicked.connect(self.handle_undo)

    def handle_tool_changed(self, tool):
        self.active = tool == "preset"

        self.clear_preview_spots()
        self.update_preview_cursor()

    def cleanup(self):
        """Release canvas subscriptions and scene items before deleting the dock."""
        self._canvas_connections.disconnect_all()
        self.hide_tooltip()
        if self.preview.preview_layer is not None:
            self.preview.remove_objects()
        self.preview.cleanup_old_layers()
        if self.rb_line is not None:
            self.canvas.scene().removeItem(self.rb_line)
            sip.delete(self.rb_line)
            self.rb_line = None

    def init_preset_layer_combobox(self, newLayer=None):
        if self.reorder_preview:
            return
        self.reorder_preview = True
        try:
            cmb_preset = self.dock.Cmb_Preset_Layer
            selected_layer = cmb_preset.currentData()
            preferred = newLayer if newLayer is not None else selected_layer
            try:
                preferred_id = preferred.id() if preferred is not None else None
            except RuntimeError:
                # The selected QGIS layer may already have been removed.
                preferred_id = None

            layers = [
                layer
                for layer in self.lt.get_vector_point_layers()
                if "Comment" in self.lt.get_fields(layer) and layer.renderer().type() == "singleSymbol"
            ]

            was_blocked = cmb_preset.blockSignals(True)
            try:
                cmb_preset.clear()
                for layer in layers:
                    cmb_preset.addItem(layer.name(), layer)

                if not layers:
                    self.preset_layer = None
                    self.preview.update_layer(None)
                    self.preview.reset()
                    return

                new_index = next(
                    (index for index, layer in enumerate(layers) if layer.id() == preferred_id),
                    0,
                )
                cmb_preset.setCurrentIndex(new_index)
                self.preset_layer = layers[new_index]
            finally:
                cmb_preset.blockSignals(was_blocked)

            self.handle_change_preset_layer(new_index)
            self.preview.create()
            self.update_preview_cursor()
        finally:
            self.reorder_preview = False

    def handle_change_preset_layer(self, idx=-1):
        if idx < 0:
            return

        layer = self.get_preset_layer()
        if layer is None:
            return
        self.preset_layer = layer
        self.preview.update_layer(layer)
        self.clear_preview_spots()

        ssps = self.get_ss_ps()

        # Load both fields before applying sizes, avoiding intermediate writes.
        self.set_value_without_signal(self.dock.Spn_Preset_Pixel_Size, ssps["ps"])
        self.set_value_without_signal(self.dock.Spn_Preset_Spot_Size, ssps["ss"])
        self.handle_change_pixel_size(ssps["ps"])

    def create_preset_layer(self):
        project_path = os.path.dirname(QgsProject.instance().fileName())
        path, _filter = QFileDialog.getSaveFileName(
            None, "Save a Shape file", os.path.join(project_path, "preset.shp"),
            "ESRI Shapefile (*.shp)",
        )
        if not path:
            return

        layer_names = {layer.name() for layer in self.lt.get_vector_point_layers()}
        name = "Preset"
        suffix = 1
        while name in layer_names:
            suffix += 1
            name = f"Preset_{suffix}"
        try:
            layer = create_layer(
                path, name, self.canvas.mapSettings().destinationCrs(),
                self.dock.Spn_Preset_Spot_Size.value(),
                self.dock.Spn_Preset_Pixel_Size.value(), self.scale,
            )
        except ValueError as error:
            QMessageBox.warning(self.dock, "Create Preset Layer", str(error))
            return

        # Register only after styling; legend callbacks can run synchronously.
        project = QgsProject.instance()
        project.addMapLayer(layer)
        self.setActiveLayer.emit(layer)
        project.layerTreeRoot().findLayer(layer.id()).setCustomProperty("showFeatureCount", True)
        self.init_preset_layer_combobox(layer)
        self.update_preview_cursor()

    def store_ss_ps(self, data):
        return write_sizes(self.preset_layer, data["ss"], data["ps"])

    def get_ss_ps(self):
        return read_sizes(self.preset_layer)

    def handle_change_pixel_size(self, size):
        if size <= 0:
            return
        self.scale = 1 / size
        ss = self.dock.Spn_Preset_Spot_Size.value()
        self.handle_change_spot_size(ss)
        if self.current_preset_mode == "grid":
            self.update_grid()
        elif self.current_preset_mode == "line":
            self.update_line()

    def handle_set_pixel_size(self, px_size):
        # call from PST (Set Pixel Size button)
        # set pixel size and select numbers
        self.dock.Spn_Preset_Pixel_Size.setValue(px_size)
        self.dock.Spn_Preset_Pixel_Size.selectAll()

        # activate Preset tab
        self.dock.Tab_Tool.setCurrentIndex(1)

    def handle_change_spot_size(self, size):
        layer = self.get_preset_layer()
        if layer is None:
            return
        self.preset_layer = layer

        set_symbol_size(layer, self.scale * size)

        ss = self.dock.Spn_Preset_Spot_Size.value()
        ps = self.dock.Spn_Preset_Pixel_Size.value()

        # save spot and pixel size to the attribute table (shapefile) as field names
        self.store_ss_ps({"ss": ss, "ps": ps})

        self.preview.update_symbol_size(self.scale, ss)
        self.update_preview_spots()

    def update_preview_spots(self):
        if not self.active:
            return

        if self.current_preset_mode == "grid":
            self.update_grid()
        elif self.current_preset_mode == "line":
            self.update_line()

    def reset_current_number(self, btn):
        # hit reset button => btn = bool
        # comment changed => btn = unicode
        if isinstance(btn, str) and not self.dock.Cbx_Reset_Increment_Number.isChecked():
            return
        self.dock.Spn_Current_Number.setValue(1)

    def get_preset_layer(self):
        layer = self.dock.Cmb_Preset_Layer.itemData(self.dock.Cmb_Preset_Layer.currentIndex())
        return layer

    def handle_change_PointPreview(self, state):
        # state 0: Unchecked, 2: Checked
        self.update_preview_cursor()

    def handle_change_CommentPreview(self, _state=None):
        self.preview.set_text_preview(self.dock.Opt_Comment_Preview.isChecked())
        if self.get_preset_mode() == "point":
            self.update_preview_cursor()

    def get_preset_mode(self, idx=-1):
        if idx < 0:
            idx = self.dock.Tab_Preset_Mode.currentIndex()
        return self.preset_modes[idx]

    def handle_preset_mode_changed(self, idx):
        if idx < 0:
            self.current_preset_mode = self.get_preset_mode()
        else:
            self.current_preset_mode = self.preset_modes[idx]
        self.clear_preview_spots()
        self.update_preview_cursor()

    def update_preview_cursor(self):
        if self.current_preset_mode != "point":
            if self.preview.cursor_marker is not None:
                self.preview.cursor_marker.hide()
            self.preview.cursor_visible = False
            editing = self.active and self.preset_layer is not None and self.alt_key
            self.canvas.setCursor(Qt.PointingHandCursor if editing else Qt.CrossCursor)
            return

        self.preview.reset()
        if not self.active or self.preset_layer is None:
            self.canvas.setCursor(Qt.CrossCursor)
            return

        if self.alt_key:
            self.canvas.setCursor(Qt.PointingHandCursor)
        elif self.shift_key:
            cursor = Qt.ClosedHandCursor if self.mouse_left and self.feature_id is not None else Qt.OpenHandCursor
            self.canvas.setCursor(cursor)
        elif self.get_preset_mode() == "point":
            show_marker = self.dock.Opt_Point_Preview.isChecked()
            show_text = self.dock.Opt_Comment_Preview.isChecked()
            if show_marker or show_text:
                self.preview.show_cursor(
                    self.cursor_pos,
                    comment=self.get_comment(0),
                    show_marker=show_marker,
                )
            self.canvas.setCursor(Qt.BlankCursor if show_marker else Qt.CrossCursor)
        else:
            self.canvas.setCursor(Qt.CrossCursor)

    def reset_preset_points(self):
        self.preview.remove_objects()
        self.preset_points = []
        self.feature_id = None
        self.update_add_points_btn_status(False)

    def add_preset_points(self):
        points = list(self.preset_points)
        if not points:
            return

        if self.dock.Cmb_Preset_Layer.currentIndex() == -1:
            return

        layer = self.get_preset_layer()
        layer.startEditing()
        fields = layer.fields()
        features = []
        for p in points:
            feature = QgsFeature()
            feature.setFields(fields)
            geom = QgsGeometry.fromPointXY(QgsPointXY(p[1], p[2]))
            comment = p[0]
            feature.setGeometry(geom)
            feature["Comment"] = comment
            features.append(feature)
        dpr = layer.dataProvider()
        results, newFeatures = dpr.addFeatures(features)
        if not results or not layer.commitChanges():
            layer.rollBack()
            return
        points_for_undo = [f.id() for f in newFeatures]
        if points_for_undo:
            self.add_to_undo("addition", points_for_undo)

        self.update_undo_btn_state()

        if self.dock.Cbx_Number_Increment.isChecked():
            self.dock.Spn_Current_Number.setValue(self.dock.Spn_Current_Number.value() + len(points))

        self.clear_preview_spots()

    def add_preset_point(self, pt):
        comment = self.get_comment(0)
        if self.dock.Opt_Comment_Popup.isChecked():
            comment, okPressed = QInputDialog.getText(None, "Input Comment", "Comment: ", QLineEdit.Normal, comment)
            if not okPressed:
                return
        self.preset_points = [[comment, pt[0], pt[1]]]
        self.preview.remove_objects()
        self.add_preset_points()

        # Show the comment for the next spot.
        self.cursor_pos = pt
        self.update_preview_cursor()

    def add_to_undo(self, undo_type, data):
        layer = self.get_preset_layer()
        if layer is None:
            return
        undo_data = {"type": undo_type, "data": data, "layer_id": layer.id()}
        self.undo_preset.append(undo_data)
        if len(self.undo_preset) > self.undo_max:
            del self.undo_preset[0]

    def handle_undo(self):
        while self.undo_preset:
            undo_item = self.undo_preset[-1]
            preset_layer = QgsProject.instance().mapLayer(undo_item["layer_id"])
            if preset_layer is not None:
                break
            self.undo_preset.pop()
        else:
            self.update_undo_btn_state()
            return

        if not preset_layer.startEditing():
            return
        self.undo_preset.pop()

        if undo_item["type"] == "addition":
            self.undo_add_preset_point(preset_layer, undo_item["data"])
        elif undo_item["type"] == "movement":
            self.undo_moving_point(preset_layer, undo_item["data"])
        elif undo_item["type"] == "comment":
            self.undo_editing_comment(preset_layer, undo_item["data"])
        elif undo_item["type"] == "delete":
            self.undo_delete_preset_point(preset_layer, undo_item["data"])

        preset_layer.commitChanges()
        self.update_undo_btn_state()

    def undo_editing_comment(self, preset_layer, data):
        fid = data["id"]
        comment = data["comment"]
        field_idx = preset_layer.fields().indexOf("Comment")
        preset_layer.changeAttributeValue(fid, field_idx, comment)

    def undo_moving_point(self, preset_layer, data):
        fid = data["id"]
        geom = data["geom"]
        preset_layer.dataProvider().changeGeometryValues({fid: geom})

    def undo_delete_preset_point(self, preset_layer, data):
        fields = preset_layer.fields()
        feature = QgsFeature()
        feature.setFields(fields)
        geom = data["geometry"]
        comment = data["comment"]
        feature.setGeometry(geom)
        feature["Comment"] = comment
        dpr = preset_layer.dataProvider()
        dpr.addFeatures([feature])

    def undo_add_preset_point(self, preset_layer, id_list):
        preset_layer.deleteFeatures(id_list)

        # update increment number
        current_layer = self.get_preset_layer()
        if (
            self.dock.Cbx_Number_Increment.isChecked()
            and current_layer is not None
            and current_layer.id() == preset_layer.id()
        ):
            spn = self.dock.Spn_Current_Number
            spn.setValue(spn.value() - len(id_list))

    def update_undo_btn_state(self):
        self.dock.Btn_Undo_Add_Preset_Point.setEnabled(bool(self.undo_preset))

    def clear_preview_points(self):
        self.init_rb_line()

    def clear_preview_spots(self, init=True):
        # clear/init all preview related items
        self.start_point = []
        self.end_point = []
        self.feature_id = None
        self.line_in_progress = False
        self.last_line_preview_at = 0.0
        self.reset_preset_points()
        if init:
            self.preview.reset()
        self.clear_preview_points()

    def init_rb_line(self):
        self.rb_line.reset()
        self.rb_line.setWidth(2)
        self.rb_line.setColor(QColor(255, 20, 20, 60))
        self.dock.Txt_Line_Length.setText("0")

    def show_tooltip(self, situ):
        self.hide_tooltip()

        pos = QCursor.pos()

        if situ == "line-start":
            txt = "🌱 Click end-point to see preview spots!"
        elif situ == "line-end":
            txt = "🌱 If the preview spots look good,\n" '🌱 click the "Add Points" button➡️'
        else:
            txt = ""
        QToolTip.showText(pos, txt, self.canvas, QRect(pos.x(), pos.y(), 200, 200), 30000)

    def hide_tooltip(self):
        QToolTip.hideText()

    def update_add_points_btn_status(self, status, reason=""):
        for mode, btn, label in (
            ("line", self.dock.Btn_Line_Add_Points, self.dock.Status_Line),
            ("grid", self.dock.Btn_Grid_Add_Points, self.dock.Status_Grid),
        ):
            enabled = status and self.current_preset_mode == mode
            btn.setEnabled(enabled)
            btn.setToolTip(reason if mode == self.current_preset_mode and not enabled else "")
            if mode != self.current_preset_mode:
                continue
            if enabled:
                label.setText(f"{len(self.preset_points):,} spots ready to add.")
            elif reason:
                label.setText(reason)
            elif mode == "line" and self.line_in_progress:
                label.setText("Click the map to set the end point.")
            else:
                label.setText("Click the map to choose the first spot.")

    def preset_line(self, pt, line_end=False, live_preview=False):
        if line_end:
            self.end_point = pt
            self.draw_line_points(live_preview)  # preview spots
            if not live_preview:
                self.line_in_progress = False
        else:  # start line drawing
            self.init_rb_line()
            self.preview.remove_objects()
            self.preset_points = []
            self.start_point = pt
            self.end_point = []
            self.preview.add_points([[pt, ""]])
            self.line_in_progress = True
            self.update_add_points_btn_status(False)

            self.rb_line.addPoint(self.start_point, False)
            self.rb_line.addPoint(self.start_point, True)

    def update_line(self):
        if len(self.start_point) and len(self.end_point):
            self.draw_line_points(live_preview=self.line_in_progress)

    def handle_line_spacing_mode_changed(self, use_step_size):
        number_field = self.dock.Spn_Line_N_Spot
        was_blocked = number_field.blockSignals(True)
        try:
            number_field.setMinimum(1 if use_step_size else 2)
        finally:
            number_field.blockSignals(was_blocked)
        self.update_line()

    def draw_line_points(self, live_preview=False):
        if not self.start_point or not self.end_point or self.scale <= 0:
            return
        self.update_line_length(self.end_point)
        self.preview.remove_objects()
        self.preset_points = []
        use_step = self.dock.Opt_Line_Step_Size.isChecked()
        try:
            placement = line_positions(
                self.start_point, self.end_point, self.scale,
                step=self.dock.Spn_Line_Step_Size.value() if use_step else None,
                count=None if use_step else self.dock.Spn_Line_N_Spot.value(),
                limit=self.max_preset_points,
            )
        except ValueError as error:
            if self.start_point == self.end_point:
                self.preview.add_points([[self.start_point, ""]])
            self.update_add_points_btn_status(False, str(error))
            return

        if use_step:
            self.set_value_without_signal(self.dock.Spn_Line_N_Spot, len(placement.points))
        else:
            self.set_value_without_signal(self.dock.Spn_Line_Step_Size, round(placement.step))
        self._show_placement(placement.points, ready=not live_preview)

    def preset_grid(self, pt):
        self.start_point = pt
        self.init_rb_line()
        self.preview.reset()
        self.draw_grid_points()

    def update_grid(self):
        if len(self.start_point) == 0:
            return

        self.preset_points = []
        self.preview.remove_objects()
        self.init_rb_line()
        self.draw_grid_points()

    def draw_grid_points(self):
        if not self.start_point:
            return
        try:
            points = self.calculate_grid_positions(
                self.start_point,
                [self.dock.Spn_Grid_Step_Size_X.value(), self.dock.Spn_Grid_Step_Size_Y.value()],
                [self.dock.Spn_Grid_N_Point_X.value(), self.dock.Spn_Grid_N_Point_Y.value()],
                self.dock.Cmb_Grid_Move_Order.currentIndex(), self.scale, self.canvas.rotation(),
            )
        except ValueError as error:
            self.update_add_points_btn_status(False, str(error))
            return
        self._show_placement(points, ready=True, draw_path=True)

    def _show_placement(self, points, ready, draw_path=False):
        """Apply comments and share the Line/Grid preview and add-button state."""
        preview_points = []
        self.preset_points = []
        for index, (x, y) in enumerate(points):
            point = QgsPointXY(x, y)
            comment = self.get_comment(index)
            preview_points.append([point, comment])
            if draw_path:
                self.rb_line.addPoint(point, True)
            if ready:
                self.preset_points.append([comment, x, y])
        self.preview.add_points(preview_points)
        self.update_add_points_btn_status(ready)

    def calculate_grid_positions(self, start_xy, step_xy, n_xy, order, scale=1, rotation=0):
        return grid_positions(start_xy, step_xy, n_xy, order, scale, rotation, self.max_preset_points)

    def set_value_without_signal(self, target, value):
        was_blocked = target.blockSignals(True)
        try:
            target.setValue(value)
        finally:
            target.blockSignals(was_blocked)

    def handle_comment_change_preview(self):
        current_mode = self.get_preset_mode()
        if current_mode == "point":
            self.preview.update_comment(self.get_comment(0))
        elif current_mode == "line":
            self.update_line()
        elif current_mode == "grid":
            self.update_grid()

    def get_comment(self, n):
        comment_base = self.dock.Tbx_Comment.text()
        flag_comment_format = self.dock.Cbx_Number_Increment.isChecked()
        current_num = self.dock.Spn_Current_Number.value()
        if not flag_comment_format:
            return comment_base
        return self.format_comment(comment_base, current_num + n)

    def format_comment(self, comment, num):
        try:
            out = comment.format(num)
        except (IndexError, KeyError, ValueError):
            out = comment
        return out

    def update_line_length(self, pt=None):
        if pt is None:
            length = 0
        else:
            length = CoordinateTool.get_distance(self.start_point, pt) / self.scale
        self.dock.Txt_Line_Length.setText(f"{length:.1f}")
        return length

    def get_near_features(self, layer, geom):
        # radius = spot_size / 2 / pixel_size (10 / 2 / 1 = 5)
        spot_size = self.dock.Spn_Preset_Spot_Size.value()
        pixel_size = self.dock.Spn_Preset_Pixel_Size.value()
        if pixel_size <= 0:
            return []
        radius = spot_size / 2 / pixel_size
        dp = layer.dataProvider()
        features = dp.getFeatures()

        out = [f for f in features if 0 <= geom.distance(f.geometry()) < radius]
        return out

    def delete_spot(self, layer, f_id, comment):
        title = "Delete Spot"
        label = f'Are you sure you want to delete "{comment}"?'

        # show confirmation dailog
        rep_message = QMessageBox.warning(None, title, label, QMessageBox.Yes | QMessageBox.No, QMessageBox.No)

        if rep_message == QMessageBox.No:
            return False

        layer.startEditing()
        layer.deleteFeature(f_id)
        layer.commitChanges()

        return True

    def delete_spot_at(self, event):
        """Delete the spot under an Alt+Shift click and keep it undoable."""
        layer = self.get_preset_layer()
        if layer is None:
            return
        cursor_geom = QgsGeometry.fromPointXY(event.mapPoint())
        features = self.get_near_features(layer, cursor_geom)
        if not features:
            return
        feature = features[-1]
        comment = feature["Comment"]
        if self.delete_spot(layer, feature.id(), comment):
            self.add_to_undo(
                "delete",
                {"id": feature.id(), "geometry": feature.geometry(), "comment": comment},
            )
            self.update_undo_btn_state()
            self.update_preview_cursor()

    def edit_point(self, e):
        layer = self.get_preset_layer()
        if layer is None:
            return

        cursor_geom = QgsGeometry.fromPointXY(e.mapPoint())
        features = self.get_near_features(layer, cursor_geom)

        if len(features) == 0:
            return

        f_id = features[-1].id()  # select uppermost feature

        layer.selectByIds([f_id], QgsVectorLayer.SetSelection)
        f = features[-1]
        comment = f["Comment"]
        geom = f.geometry()

        # show dailog for new comment or delete spot
        params = {"comment": comment}
        self.edit_dialog = EditDialog(None, params)
        self.edit_dialog.exec_()

        # exit_state 0: Cancel, 1: OK (new comment), 2: Delete
        exit_state = self.edit_dialog.get_exit_state()

        if exit_state == 1:  # Modify Comment
            new_comment = self.edit_dialog.return_new_comment()
            self.modify_comment(layer, f_id, new_comment)
            undo_data = {"id": f_id, "comment": comment}
            self.add_to_undo("comment", undo_data)

        elif exit_state == 2:  # Delete spot
            res_delete = self.delete_spot(layer, f_id, comment)
            if res_delete:
                undo_data = {"id": f_id, "geometry": geom, "comment": comment}
                self.add_to_undo("delete", undo_data)

        layer.removeSelection()
        self.update_undo_btn_state()
        self.update_preview_cursor()

    def modify_comment(self, layer, f_id, new_comment):
        field_idx = layer.fields().indexOf("Comment")
        layer.startEditing()
        layer.changeAttributeValue(f_id, field_idx, new_comment)
        layer.commitChanges()

    def handle_escapeKey(self):
        if self.preset_layer is None:
            return

        self.clear_preview_spots(init=False)

    def handle_shift_key_state_changed(self, state):
        if state and self.shift_key:
            return
        self.shift_key = state
        if not state and self.relocating_spot:
            self.relocating_spot = False
            self.reset_preset_points()
        self.update_preview_cursor()

    def handle_shiftKey_state_changed(self, state):
        self.handle_shift_key_state_changed(state)

    def handle_altKey_state_changed(self, state):
        self.alt_key = state
        #
        # Edit spot (modify comment, delete post)
        #
        # Windows/Linux: Alt, MacOS: Option
        #
        if self.preset_layer is None:
            return

        if self.current_preset_mode in ["line", "grid"]:
            # cancel
            self.clear_preview_spots(init=False)

        self.update_preview_cursor()

    def handle_mouse_moved(self, pt: QgsPointXY):
        if not self.preset_layer:
            return

        self.cursor_pos = pt
        if self.current_preset_mode == "line" and self.line_in_progress:
            self.rb_line.removeLastPoint()
            self.rb_line.addPoint(pt, True)
            self.update_line_length(pt)
            now = time.monotonic()
            if now - self.last_line_preview_at >= self.line_preview_interval:
                self.last_line_preview_at = now
                self.preset_line(pt, line_end=True, live_preview=True)
            return
        if self.current_preset_mode == "point":
            if (self.relocating_spot and self.feature_id is not None) or self.preview.cursor_visible:
                if self.feature_id is not None:
                    pt.set(pt.x() + self.movement_offset[0], pt.y() + self.movement_offset[1])
                self.preview.update_position(pt)

    def handle_mouse_pressed(self, pt):
        self.mouse_left = True
        mode = self.get_preset_mode()
        if mode == "point":
            if self.shift_key:
                # start moving spot
                self.relocating_spot = True
                self.initiate_relocation(pt)
            else:
                self.add_preset_point(pt)

    def handle_mouse_released(self, pt):
        self.mouse_left = False
        if self.shift_key:
            self.relocating_spot = False

    def handle_clicked(self, pt, finish_line=False):
        if self.preset_layer is None:
            return
        if self.current_preset_mode == "point":
            # Point mode adds on mouse press so editing gestures cannot add a spot.
            return

        if self.current_preset_mode == "line":
            if not self.line_in_progress:
                if finish_line:
                    return
                self.clear_preview_spots(init=False)
                self.preset_line(pt)
                self.show_tooltip("line-start")
            elif CoordinateTool.get_distance(self.start_point, pt) > 0:
                self.rb_line.removeLastPoint()
                self.rb_line.addPoint(pt, True)
                self.preset_line(pt, line_end=True)
                self.show_tooltip("line-end")
            else:
                self.rb_line.removeLastPoint()
                self.rb_line.addPoint(pt, True)
                self.preset_line(pt, line_end=True, live_preview=True)
            return

        if self.current_preset_mode == "grid" and not finish_line:
            self.clear_preview_spots(init=False)
            self.preset_grid(pt)

    def initiate_relocation(self, pt):
        if not self.preset_layer:
            return

        self.preview.reset(moving=True)
        self.init_rb_line()

        # Locate the uppermost spot within its displayed radius.
        cursor_geom = QgsGeometry.fromPointXY(pt)
        self.movement_offset = [0, 0]
        features = self.get_near_features(self.preset_layer, cursor_geom)

        if len(features) == 0:
            # do nothing
            return

        self.canvas.setCursor(Qt.ClosedHandCursor)

        feature = features[-1]  # select uppermost feature
        geom = feature.geometry()
        pt = geom.asPoint()
        cursor_geom_p = cursor_geom.asPoint()
        self.movement_offset = [
            pt.x() - cursor_geom_p.x(),
            pt.y() - cursor_geom_p.y(),
        ]
        self.feature_id = feature.id()
        # Select target spot
        self.preset_layer.selectByIds([self.feature_id], QgsVectorLayer.SetSelection)

        self.preview.show_cursor(pt, moving=True, comment=feature["Comment"])

    def handle_finish_relocation(self, pt: QgsPointXY):
        if self.feature_id is None:
            return

        # Get coordinate of feature for undo
        feature = self.preset_layer.getFeature(self.feature_id)
        if not feature.isValid():
            self.reset_preset_points()
            return
        original_geo = feature.geometry()

        # movement_offset = offset between the center of the feature and cursor
        # Cursor doesn't always grab the center of the feature
        pt.set(pt.x() + self.movement_offset[0], pt.y() + self.movement_offset[1])
        geom = QgsGeometry.fromPointXY(pt)

        self.preset_layer.startEditing()
        self.preset_layer.dataProvider().changeGeometryValues({self.feature_id: geom})
        self.preset_layer.commitChanges()

        self.preset_layer.removeSelection()

        # Keep the original geometry for undo.
        undo_data = {"id": self.feature_id, "geom": original_geo}
        self.add_to_undo("movement", undo_data)

        self.preview.reset()

        # Update cursor
        self.update_preview_cursor()

        self.update_undo_btn_state()
        self.feature_id = None

    def handle_move_point_end(self, event):
        """Adapt the map-tool release event to the common relocation operation."""
        self.handle_finish_relocation(event.mapPoint())
