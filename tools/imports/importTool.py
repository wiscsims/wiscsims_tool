    def _import_from_excel(self, progress):
        progress.update("Selecting workbook rows…")

        # import date from Excel file
        if self.dock.Opt_Comment.isChecked():
            try:
                importing_data = self.xl.filter_by_comment(self.dock.Tbx_Comment_Match.text())
            except re.error as error:
                QMessageBox.warning(None, "Import Excel Data", f"Invalid comment pattern: {error}")
                return
        else:
            start_idx = self.dock.Cmb_Excel_From.currentIndex()
            end_idx = self.dock.Cmb_Excel_To.currentIndex()
            if start_idx > end_idx:
                start_idx, end_idx = end_idx, start_idx
                self.dock.Cmb_Excel_From.setCurrentIndex(start_idx)
                self.dock.Cmb_Excel_To.setCurrentIndex(end_idx)
            start_asc = self.dock.Cmb_Excel_From.itemData(start_idx)
            end_asc = self.dock.Cmb_Excel_To.itemData(end_idx)
            importing_data = self.xl.filter_by_asc(start=start_asc, end=end_asc)

        importing_layer = self.dock.Cmb_Import_Layer.itemData(self.dock.Cmb_Import_Layer.currentIndex())
        coordinate_columns = self.xl.find_columns(["X", "Y"], False)
        if coordinate_columns is None:
            QMessageBox.warning(None, "Import Excel Data", "The workbook needs X and Y columns.")
            return
        X, Y = coordinate_columns

        features_by_row = {}
        glp_failures = []
        glp_failed_rows = []
        pair_fallback_count = 0
        is_direct_import = not self.dock.Grp_Alignment.isChecked()

        use_glp = not is_direct_import and self.dock.Cmb_Import_Conversion.currentIndex() == 1
        glp_inverse = None
        if use_glp:
            progress.update("Preparing GLP alignment conversion…")
            try:
                glp_inverse = self.prepare_glp_inverse()
            except (ValueError, OverflowError) as error:
                progress.dialog.hide()
                QMessageBox.warning(self.dock, "GLP Import", f"No data were imported.\n\n{error}")
                return
        elif self.new_aliginment and not is_direct_import:
            self.update_conv_params()
            if not self.conv_params:
                QMessageBox.warning(None, "Import Excel Data", "At least two usable alignment points are needed.")
                return

        total = len(importing_data)
        fields = importing_layer.fields()
        progress.update("Checking coordinates and attributes…", 0, total)
        for index, d in enumerate(importing_data, 1):
            progress.update("Checking coordinates and attributes…", index - 1, total)
            try:
                point = [float(d[X]), float(d[Y])]
            except (TypeError, ValueError):
                continue
            if not all(math.isfinite(coordinate) for coordinate in point):
                continue
            if is_direct_import:
                canvasX, canvasY = point
            elif use_glp:
                try:
                    canvasX, canvasY = glp_inverse.predict(point)
                except (ValueError, OverflowError) as error:
                    glp_failures.append((str(d[0]), str(error)))
                    glp_failed_rows.append((index, d, point))
                    continue
            else:
                try:
                    canvasX, canvasY = self.convert_with_reference_pairs(point)
                except (ValueError, OverflowError, ZeroDivisionError) as error:
                    QMessageBox.warning(self.dock, "Import Excel Data", f"No data were imported. File: {d[0]}\n\n{error}")
                    return
            feature = QgsFeature(fields)
            feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(canvasX, canvasY)))
            try:
                feature.setAttributes(self.convert_attributes(d, fields))
            except ValueError as error:
                QMessageBox.warning(
                    None, "Import Excel Data",
                    f"No data were imported. File: {d[0]}\n\n{error}\n\n"
                    "Create a new layer from this workbook to use compatible field types.",
                )
                return

            features_by_row[index] = feature

        progress.update("Checking coordinates and attributes…", total, total)
        if glp_failures:
            progress.dialog.hide()
            action = self.review_glp_failures(glp_failures, len(features_by_row))
            if action not in ("verified", "pairs"):
                return
            progress.dialog.show()
            if action == "pairs":
                progress.update("Preparing reference-pair conversion…")
                self.update_conv_params()
                for completed, (index, row, point) in enumerate(glp_failed_rows):
                    progress.update("Converting affected points with reference pairs…", completed, len(glp_failed_rows))
                    try:
                        canvas_point = self.convert_with_reference_pairs(point)
                        feature = QgsFeature(fields)
                        feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(*canvas_point)))
                        feature.setAttributes(self.convert_attributes(row, fields))
                    except (ValueError, OverflowError, ZeroDivisionError) as error:
                        progress.dialog.hide()
                        QMessageBox.warning(
                            self.dock, "Reference-pair Import",
                            f"No data were imported. File: {row[0]}\n\n{error}",
                        )
                        return
                    features_by_row[index] = feature
                pair_fallback_count = len(glp_failed_rows)
        features = [features_by_row[index] for index in sorted(features_by_row)]
        dpr = importing_layer.dataProvider()
        progress.update(f"Writing {len(features):,} points to layer…\n{importing_layer.name()}")
        success, added_features = dpr.addFeatures(features)
        if not success:
            details = "\n".join(dpr.errors())
            QMessageBox.warning(
                None, "Import Excel Data",
                "The layer could not accept the selected data.\n\n" + details,
            )
            return
        progress.update("Updating layer display…")
        importing_layer.updateExtents()
        importing_layer.setDisplayExpression("File")
        importing_layer.triggerRepaint()
        progress.dialog.hide()
        message = f"{len(added_features)} data were imported!"
        if pair_fallback_count:
            message += f"\n{pair_fallback_count} points were converted with Current (reference pairs)."
        elif glp_failures:
            message += f"\n{len(glp_failures)} points without a verified GLP position were skipped."
        QMessageBox.information(None, "Import Excel Data", message)

    def convert_with_reference_pairs(self, point):
        """Use the same conversion for Current imports and explicit GLP fallback."""
        if self.new_aliginment:
            models = self.get_conversion_models(point, self.model.getStagePositions(), self.conv_params, 2)
            if not models:
                raise ValueError("No usable alignment pair was found.")
            result = self.cot.getWtAveragedStageToCanvas(point, models)
        else:
            result = self.getWtAverageStageToCanvas(point)
        if not all(math.isfinite(value) for value in result):
            raise ValueError("Reference-pair conversion produced non-finite coordinates.")
        return result

    def review_glp_failures(self, failures, verified_count):
        """Choose how to handle failed inverses before writing any features."""
        box = QMessageBox(self.dock)
        box.setWindowTitle("GLP Import")
        box.setIcon(QMessageBox.Warning)
        box.setText(
            f"{len(failures):,} points could not be assigned a verified GLP position.\n"
            f"{verified_count:,} points have verified positions. No data have been imported yet."
        )
        box.setInformativeText(
            f"First affected file: {failures[0][0]}\n\n"
            "Open Details to review all affected files. Check that the alignment and enabled "
            "references match the GLP export. Choose reference pairs to import the affected "
            "points with Current (reference pairs), import only verified GLP points, or cancel. "
            "Pair-converted points use a different model and are not verified GLP positions."
        )
        box.setDetailedText("\n\n".join(f"File: {name}\n{error}" for name, error in failures))
        import_button = None
        if verified_count:
            import_button = box.addButton(f"Import {verified_count:,} verified points", QMessageBox.AcceptRole)
        pair_button = box.addButton("Use reference pairs for affected points", QMessageBox.ActionRole)
        cancel_button = box.addButton(QMessageBox.Cancel)
        box.setDefaultButton(cancel_button)
        box.setEscapeButton(cancel_button)
        box.exec_()
        action = "cancel"
        if box.clickedButton() is pair_button:
            action = "pairs"
        elif import_button is not None and box.clickedButton() is import_button:
            action = "verified"
        box.deleteLater()
        return action

    def prepare_glp_inverse(self):
        if not self.new_aliginment:
            raise ValueError("GLP needs a MonkeyNavigator2 alignment, not the legacy pair format.")
        snapshot = reference_snapshot(self.model.ExportAsObject())
        if snapshot != self._glp_snapshot:
            # Invalidate first: failed preparation must never reuse an old fit.
            self._glp_inverse = None
            self._glp_snapshot = None
            if len(snapshot) < 4:
                raise ValueError(
                    f"GLP requires at least four usable references (found {len(snapshot)}). "
                    "Use the same alignment and enabled references as MonkeyNavigator2 Export."
                )
            inverse = PreparedGLPInverse([r[1] for r in snapshot], [r[2] for r in snapshot])
            self._glp_inverse = inverse
            self._glp_snapshot = snapshot
        return self._glp_inverse

    @staticmethod
    def convert_attributes(row, fields):
        """Validate the whole batch before writing any features to the provider."""
        attributes = []
        for index, field in enumerate(fields):
            value = row[index] if index < len(row) else None
            if value is None or value == "":
                value = None
            elif isinstance(value, (date, time)):
                value = value.isoformat()
            try:
                attributes.append(field.convertCompatible(value))
            except ValueError as error:
                raise ValueError(
                    f'Column "{field.name()}": {value!r} cannot be stored as {field.typeName()}.'
                ) from error
        return attributes

    def update_ref_point_markers(self):
        self.ref_marker.init_ref_point_markers()
        # shwo ref points?
        if not self.dock.Gbx_Alignment_Ref_Point_Markers.isChecked():
            return

        alignments = self.model.ExportAsObject()
        selected_alignment = self.dock.Tbv_Alignment.currentIndex().row()

        if self.new_aliginment:
            for aln in alignments:
                if aln["used"] < 2 and aln["r"] != selected_alignment:
                    continue
                current_flag = selected_alignment == aln["r"]
                if not self.is_default_values(aln["stage"]):
                    self.handle_ref_marker(aln["canvas"], aln["refname"], current_flag)
        else:
            for aln in alignments:
                current_flag = selected_alignment == aln["r"]
                self.handle_ref_marker(aln["point_1"][1], aln["refname"] + " (1)", current_flag)
                self.handle_ref_marker(aln["point_2"][1], aln["refname"] + " (2)", current_flag)
            self.update_canvas_rotation()

    def update_canvas_rotation(self):
        if self.model.isAvailable():
            params = self.model.getParams()
            if "rotation" in params:
                self.canvas.setRotation(params["rotation"])

    def handle_ref_marker(self, pt, name, current=False):
        if self.dock.Cbx_Alignment_Ref_Points.isChecked():
            self.ref_marker.add_ref_marker(pt, name, current)
        if self.dock.Cbx_Alignment_Ref_Names.isChecked():
            self.ref_marker.add_ref_marker_annotation(pt, name, current)

    def is_ok_to_import(self):
        """check importing condition"""
        if self.dock.Grp_Alignment.isChecked() and not self.model.isAvailable():
            """use alignment but no alignment file imported"""
            return False

        if self.xl is None or self.xl.ws is None:
            """no excel file"""
            return False

        if self.dock.Cmb_Import_Layer.currentIndex() == -1:
            """no layer is selected"""
            return False
        return True

    def is_default_values(self, pt):
        return pt[0] == self.default_val and pt[1] == self.default_val

    def is_identical_field_names(self, layer, xl_fields, field_max_len=5):
        pattern = re.compile(r"^[ps]s_[\d\.]+")
        my_fields = [f for f in self.lt.get_fields(layer) if not pattern.search(f)]
        my_fields_names = [f[:field_max_len] for f in my_fields]
        xl_fields_len = len(self.intersect(my_fields_names, xl_fields))
        return xl_fields_len == len(my_fields)

    def get_excel_layers(self, xl):
        field_max_len = 5
        pattern = re.compile(r"^[ps]s_[\d\.]+")
        # field names in vector layers have been chopped
        if xl.ws is None:
            return []
        xl_fields = [h[:field_max_len] for h in xl.get_headers() if not pattern.search(h)]
        legend = QgsProject.instance().layerTreeRoot()
        try:
            vec_layers = self.lt.get_vector_point_layers()
            layers = [layer for layer in vec_layers if legend.findLayer(layer.id()).isVisible()]
        except Exception:
            return []

        return [layer for layer in layers if self.is_identical_field_names(layer, xl_fields, field_max_len)]

    def intersect(self, list1, list2):
        return [lst for lst in list1 if lst in list2]

    def get_average(self, arr):
        return sum(arr) / len(arr) * 1.0

    def getWtAverageStageToCanvas(self, pt):
        model = self.model.ExportAsObject()
        weights, wpt_x, wpt_y, np = [], [], [], [0, 0]
        tmp_out = []
        for m in model:
            if m["used"] == 0:
                continue
            params = [m["scale"], m["offset"], m["rotation"]]
            for i in [1, 2]:
                pt_name = "point_" + str(i)
                d = self.cot.getDistance(pt, m[pt_name][0])
                if d == 0:
                    d = 1e-10
                w = 1.0 / (d**2)
                if i == 1:
                    np = self.cot.toCanvasCoordinates2(pt, params)
                tmp_out.append(w)
                weights.append(w)
                wpt_x.append(w * np[0])
                wpt_y.append(w * np[1])
        sum_weights = sum(weights)
        return [p / sum_weights for p in [sum(wpt_x), sum(wpt_y)]]

    def update_conv_params(self):
        self.conv_params = {}
        if self.model.isAvailable():
            # Get available rows (indexes)
            available_refs = self.model.getAvailableRows()
            for g in available_refs:
                for r in available_refs:
                    if g >= r:
                        continue
                    # Get combinations of indexes
                    key = f"{g}-{r}"
                    # Calculate ConvertParams
                    try:
                        scale, offset, rotation = self.cot.getConvertParams(
                            self.model.getStagePosition(g),
                            self.model.getCanvasPosition(g),
                            self.model.getStagePosition(r),
                            self.model.getCanvasPosition(r),
                        )
                    except ZeroDivisionError:
                        continue
                    self.conv_params[key] = {
                        "scale": scale,
                        "offset": offset,
                        "rotation": rotation,
                    }

            self.update_canvas_rotation()
        self.update_ref_point_markers()

    def sort_by_distance(self, pt, ref_canvas_pt):
        out = {}
        if not isinstance(pt, QgsPointXY):
            pt = QgsPointXY(pt[0], pt[1])
        for k, v in ref_canvas_pt.items():
            out[k] = pt.distance(v[0], v[1])
        # sorted by distance
        retval = [(k, v) for k, v in sorted(out.items(), key=lambda item: item[1])]
        return retval

    def get_conversion_models(self, pt, ref_pos, conv_params, limit=2):
        sorted_idxes = self.sort_by_distance(pt, ref_pos)
        pairs = []
        for index, (first_row, first_distance) in enumerate(sorted_idxes):
            for second_row, second_distance in sorted_idxes[index + 1 :]:
                low, high = sorted((first_row, second_row))
                key = f"{low}-{high}"
                if key in conv_params:
                    pairs.append((first_distance + second_distance, key))
        pairs.sort()
        if limit >= 2:
            pairs = pairs[: max(1, limit * (limit - 1) // 2)]
        return [
            {**conv_params[key], "weight": 1 / max(distance, 1e-10) ** 2}
            for distance, key in pairs
        ]
