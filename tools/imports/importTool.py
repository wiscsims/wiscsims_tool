    def create_new_layer(self, fpath=None):
        project_path = os.path.dirname(QgsProject.instance().fileName())
        saveFile, _ = QFileDialog.getSaveFileName(None, "Save a Shape file", project_path, "ESRI Shapefile (*.shp)")

        if saveFile == "":
            return None

        vl = QgsVectorLayer("Point", "temporary_points", "memory")
        vl.setCrs(self.canvas.mapSettings().destinationCrs())
        vl.setProviderEncoding("UTF-8")
        pr = vl.dataProvider()
        labels = self.xl.get_headers()
        rows = self.xl.filter_by_asc()
        attrs = [
            QgsField(label, self.lt.get_field_type(label, (row[index] for row in rows)))
            for index, label in enumerate(labels)
        ]

        pr.addAttributes(attrs)
        vl.setDisplayExpression("File")
        vl.updateFields()

        reg = QgsProject.instance()
        # Remove layers which have same souce file as shape file to be overwritten
        for layer in self.lt.get_layer_list(layertype=0):
            if layer.source() == saveFile:
                reg.removeMapLayer(layer.id())

        # write shape + etc files
        error, _ = QgsVectorFileWriter.writeAsVectorFormat(vl, saveFile, "UTF-8", vl.crs(), "ESRI Shapefile")
        if not fpath:
            fpath = self.xl.get_workbook_name()
        parsedPath = os.path.basename(fpath).split(".")[:-1]
        layerName = ".".join(parsedPath)
        text, okPressed = QInputDialog.getText(None, "Input Layer Name", "Layer name: ", QLineEdit.Normal, layerName)
        if okPressed:
            layerName = text

        if error == QgsVectorFileWriter.NoError:
            newVlayer = QgsVectorLayer(saveFile, layerName, "ogr")
            newVlayer.setCustomProperty("workbookPath", fpath)
            props = newVlayer.renderer().symbol().symbolLayer(0).properties()
            props["name"] = "circle"
            props["size_unit"] = "MapUnit"
            props["offset_unit"] = "MapUnit"
            props["outline_width_unit"] = "MapUnit"
            spotSize = 1.0 * self.dock.Spn_Spot_Size.value()
            if self.model.isAvailable():
                scale = self.get_average(self.model.getScales())
            else:
                scale = 1.0
            # scale = self.ct[self.getNavAlign()].scale / 1.0
            props["size"] = str(spotSize / scale)
            mySimpleSymbol = QgsMarkerSymbol.createSimple(props)
            newVlayer.renderer().setSymbol(mySimpleSymbol)
            newVlayer.updateExtents()
            QgsProject.instance().addMapLayer(newVlayer)
            # emit set_active_layer
            self.setActiveLayer.emit(newVlayer)

            # self.iface.setActiveLayer(newVlayer)
            self.update_import_layers()
            self.dock.Cmb_Import_Layer.setCurrentIndex(self.dock.Cmb_Import_Layer.findText(layerName))
            return newVlayer

        return None

    def select_workbook(self):
        title = "Select WiscSIMS Session Workbook"
        mypath = os.path.dirname(QgsProject.instance().fileName())
        workbook_path, _ = QFileDialog.getOpenFileName(None, title, mypath, "Excel (*.xls *.xlsx)")

        if workbook_path == "":
            return
        if self.prev_workbook_path == workbook_path:
            return
        if not self.dependency_installer.ensure_excel_reader(workbook_path):
            return

        with OperationProgress(self.dock, "Read Excel Workbook") as progress:
            progress.update(f"Opening Excel workbook…\n{os.path.basename(workbook_path)}")
            try:
                workbook = progress.run_in_background(
                    lambda report: self.read_workbook(workbook_path, report)
                )
            except Exception as error:
                QMessageBox.warning(self.dock, "Excel File Selection", f"Could not read the workbook.\n\n{error}")
                return
            if workbook.ws is not None:
                progress.update("Updating workbook controls…")
                self.xl = workbook
                self.workbook_path = workbook_path
                self.prev_workbook_path = workbook_path
                self.dock.Tbx_Workbook.setText(os.path.basename(workbook_path))
                self.dock.Tbx_Workbook.setToolTip(workbook_path)
        if workbook.ws is None:
            QMessageBox.warning(
                None,
                "Excel File Selection",
                "Could not read the workbook. It needs a sheet named Sum_table or Data.\n\n"
                f"{workbook.load_error or ''}",
            )
            return

    @staticmethod
    def read_workbook(path, progress):
        """Read Python-only workbook data before updating any QGIS widgets."""
        workbook = SumTableTool(path)
        if workbook.ws is not None:
            workbook.get_headers()
            workbook.get_values(progress=progress)
        return workbook

